// Bundles lib/host-json-collector-runtime.ts into a self-contained source string
// so the host scan never depends on how bb re-bundles the plugin server.
// `node scripts/build-host-json-collector.mjs` rewrites the generated module;
// `--check` exits non-zero when it is stale.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
export const RUNTIME_ENTRY = `${root}lib/host-json-collector-runtime.ts`;
export const GENERATED_MODULE = `${root}lib/host-json-collector.generated.ts`;
export const COLLECTOR_GLOBAL = "__bbUsageHostCollector";

export async function renderHostJsonCollectorModule() {
  const result = await build({
    entryPoints: [RUNTIME_ENTRY],
    bundle: true,
    write: false,
    format: "iife",
    globalName: COLLECTOR_GLOBAL,
    platform: "node",
    target: "node18",
    minify: true,
    legalComments: "none",
    logLevel: "silent",
  });
  const source = result.outputFiles[0].text.trim();
  return [
    "// Generated by scripts/build-host-json-collector.mjs from host-json-collector-runtime.ts. Do not edit.",
    `export const HOST_JSON_COLLECTOR_GLOBAL = ${JSON.stringify(COLLECTOR_GLOBAL)};`,
    `export const HOST_JSON_COLLECTOR_SOURCE = ${JSON.stringify(source)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = await renderHostJsonCollectorModule();
  if (process.argv.includes("--check")) {
    const current = await readFile(GENERATED_MODULE, "utf8").catch(() => "");
    if (current !== rendered) {
      console.error("lib/host-json-collector.generated.ts is stale; run `npm run build:collector`.");
      process.exit(1);
    }
  } else {
    await writeFile(GENERATED_MODULE, rendered);
  }
}
